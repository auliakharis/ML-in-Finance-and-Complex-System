"""
run_llm_eval_api_call_adversarial.py
=====================================
Evaluates an LLM on the 90-Q financial QA dataset using adversarially corrupted
spreadsheets as context.  The questions and ground-truth answers are always taken
from the clean 90-Q questions file; only the financial spreadsheet shown to the
model changes across runs.

Five adversarial sheet variants (generated by compiler_pipeline_refactored/adversarial.py):
  baseline     — original clean spreadsheet
  missing      — non-question cells replaced with empty strings
  garbage      — non-question cells replaced with extreme/nonsense values
  lookalike    — digits in non-question cells swapped with look-alike characters (e.g. 1→I, 0→O)
  cross        — non-question cells replaced with real values from a different company/year
  combined     — all four corruption types mixed equally

For each question a prompt is built:
  "ROLE: Financial analyst. Answer using ONLY the data below. ...
   [adversarial company spreadsheet]
   QUESTION: [question]
   RULES: ..."

Accuracy is the fraction of answers within a relative tolerance of the ground-truth
numeric answer (default ±10%).

Usage:
  python run_llm_eval_api_call_adversarial.py
  python run_llm_eval_api_call_adversarial.py --limit 20 --tol 0.05
  python run_llm_eval_api_call_adversarial.py --datasets missing garbage
  python run_llm_eval_api_call_adversarial.py --models Qwen/Qwen3.5-27B --output results.json
"""

import argparse
import csv
import json
import os
import re
import sys
from datetime import datetime
from pathlib import Path

import openai
from dotenv import load_dotenv

load_dotenv()

_client = openai.Client(
    api_key=os.environ.get("CSCS_SERVING_API"),
    base_url="https://api.swissai.svc.cscs.ch/v1",
)

# ---------------------------------------------------------------------------
# Paths
# ---------------------------------------------------------------------------

BASE_DIR = Path(__file__).parent

DATASET_90Q = BASE_DIR / "compiler_pipeline_refactored" / "output"/ "random_questions_90.json"

ADV_DIR = BASE_DIR / "compiler_pipeline_refactored" / "output" / "adversarial"
CLEAN_SHEET = BASE_DIR / "compiler_pipeline_refactored" / "output" / "synthetic_company_data.csv"

ADVERSARIAL_SHEETS: dict[str, Path] = {
    "baseline": CLEAN_SHEET,
    "missing":  ADV_DIR / "missing_values.csv",
    "garbage":  ADV_DIR / "garbage.csv",
    "lookalike": ADV_DIR / "lookalike.csv",
    "cross":    ADV_DIR / "cross_contaminated.csv",
    "combined": ADV_DIR / "combined_adversarial.csv",
}

DEFAULT_MODELS = ["Qwen/Qwen3.5-27B"]


# ---------------------------------------------------------------------------
# Data loading
# ---------------------------------------------------------------------------

def load_json(path: Path) -> list:
    with open(path) as f:
        return json.load(f)


def load_sheet_csv(path: Path) -> list[dict]:
    """Load a synthetic company data CSV (clean or adversarial) as a list of row dicts."""
    with open(path, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def build_sheet_lookup(rows: list[dict]) -> dict:
    """company_name -> list of rows (one per year), sorted by year."""
    lookup: dict = {}
    for row in rows:
        name = row.get("company_name") or row.get("entity", "")
        lookup.setdefault(name, []).append(row)
    for name in lookup:
        lookup[name].sort(key=lambda r: r.get("year", "0"))
    return lookup


# ---------------------------------------------------------------------------
# Prompt builder
# ---------------------------------------------------------------------------

def sheet_to_text(rows: list) -> str:
    """Format multiple annual rows for a company as readable text."""
    if not rows:
        return "(no data)"
    lines = []
    for row in rows:
        year = row.get("year", "?")
        lines.append(f"  Year {year}:")
        for k, v in row.items():
            if k not in ("company_name", "year"):
                lines.append(f"    {k}: {v}")
    return "\n".join(lines)


def build_prompt(sheet_text: str, question: str) -> str:
    return (
        "ROLE: Financial analyst. Answer using ONLY the data below. No commentary.\n\n"
        "=== DATA ===\n"
        f"{sheet_text}\n"
        "=== END ===\n\n"
        f"QUESTION: {question}\n\n"
        "RULES:\n"
        "- Extract only the numbers you need.\n"
        "- Show calculations in 1–3 lines max if needed.\n"
        "- Last line MUST be: Answer: <value>\n"
        "- <value> is either a number, True, or False. Nothing else.\n"
        "- Do NOT explain, summarize, or add anything after the Answer line.\n"
        "- Do NOT show your thinking process.\n\n"
        "SOLVE NOW:"
    )


# ---------------------------------------------------------------------------
# Answer extraction
# ---------------------------------------------------------------------------

def extract_number(text: str) -> float | bool | None:
    match = re.search(r'Answer\s*:\s*(.+)', text, re.IGNORECASE)
    if match:
        raw = match.group(1).strip().rstrip(".,;")
        if raw.lower() == "true":
            return True
        if raw.lower() == "false":
            return False
        cleaned = re.sub(r'(\d),(\d)', r'\1\2', raw)
        num_match = re.search(r'-?\d+(?:\.\d+)?(?:[eE][+-]?\d+)?', cleaned)
        if num_match:
            return float(num_match.group())
    cleaned = re.sub(r'(\d),(\d)', r'\1\2', text)
    matches = re.findall(r'-?\d+(?:\.\d+)?(?:[eE][+-]?\d+)?', cleaned)
    return float(matches[-1]) if matches else None


def is_correct(predicted, ground_truth, tol: float) -> bool:
    if predicted is None or ground_truth is None:
        return False
    if isinstance(predicted, bool) or isinstance(ground_truth, bool):
        return predicted == ground_truth
    if isinstance(ground_truth, str):
        try:
            ground_truth = float(ground_truth.replace(",", ""))
        except ValueError:
            return False
    if ground_truth == 0:
        return abs(predicted) < 1e-6
    return abs(predicted - ground_truth) / abs(ground_truth) <= tol


# ---------------------------------------------------------------------------
# LLM inference
# ---------------------------------------------------------------------------

def strip_thinking_tags(text: str) -> str:
    parts = re.split(r'<\|message\|>', text)
    if len(parts) > 1:
        last = parts[-1]
        last = re.sub(r'<\|[^|]*\|>', '', last)
        return last.strip()
    text = re.sub(r'<\|(?!end\|)[^|]*\|>.*?<\|end\|>', '', text, flags=re.DOTALL)
    text = re.sub(r'<\|[^|]*\|>', '', text)
    return text.strip()


def run_inference(model_name: str, prompt: str, max_new_tokens: int = 2048) -> str:
    response = _client.chat.completions.create(
        model=model_name,
        messages=[
            {"role": "system", "content": "Do not show your thinking process. Output only the answer."},
            {"role": "user", "content": prompt},
        ],
        max_tokens=max_new_tokens,
        extra_body={"chat_template_kwargs": {"enable_thinking": False}},
    )
    return response.choices[0].message.content.strip()


# ---------------------------------------------------------------------------
# Evaluation loop
# ---------------------------------------------------------------------------

def evaluate(
    questions: list,
    sheet_lookup: dict,
    model_name: str,
    dataset_label: str,
    limit: int | None,
    tol: float,
    max_new_tokens: int = 2048,
) -> list:
    """Evaluate questions against a given sheet lookup. Returns per-question result dicts."""
    results = []
    subset = questions[:limit] if limit else questions

    for i, q in enumerate(subset, 1):
        entity = q.get("entity") or q.get("leaf_1_entity", "")
        question_text = q.get("question", "")
        ground_truth = q.get("answer")

        sheet_rows = sheet_lookup.get(entity)
        if not sheet_rows:
            print(f"  [{i}/{len(subset)}] SKIP (no sheet for '{entity}')")
            results.append({
                "dataset": dataset_label,
                "id": q.get("id") or q.get("question_id"),
                "entity": entity,
                "depth": q.get("depth"),
                "question": question_text,
                "ground_truth": ground_truth,
                "llm_response": None,
                "predicted": None,
                "correct": False,
                "skip": True,
            })
            continue

        sheet_text = sheet_to_text(sheet_rows)
        prompt = build_prompt(sheet_text, question_text)
        response = run_inference(model_name, prompt, max_new_tokens)
        predicted = extract_number(response)
        correct = is_correct(predicted, ground_truth, tol)

        status = "CORRECT" if correct else "WRONG "
        try:
            gt_display = f"{float(ground_truth):.4f}"
        except (TypeError, ValueError):
            gt_display = str(ground_truth)
        print(f"  [{i}/{len(subset)}] {status} | truth={gt_display} pred={predicted} | {question_text[:60]}...")

        results.append({
            "dataset": dataset_label,
            "id": q.get("id") or q.get("question_id"),
            "entity": entity,
            "depth": q.get("depth"),
            "question": question_text,
            "ground_truth": ground_truth,
            "prompt": prompt,
            "llm_response": response,
            "predicted": predicted,
            "correct": correct,
            "skip": False,
        })

    return results


# ---------------------------------------------------------------------------
# Accuracy summary
# ---------------------------------------------------------------------------

def compute_accuracy(results: list) -> dict:
    evaluated = [r for r in results if not r.get("skip")]
    if not evaluated:
        return {"total": 0, "correct": 0, "accuracy": 0.0, "skipped": len(results)}
    correct = sum(1 for r in evaluated if r["correct"])
    return {
        "total": len(evaluated),
        "skipped": len(results) - len(evaluated),
        "correct": correct,
        "accuracy": correct / len(evaluated),
    }


def print_summary(model_name: str, all_results: dict[str, list]) -> None:
    print(f"\n{'='*65}")
    print(f"  Model: {model_name}")
    print(f"{'='*65}")
    print(f"  {'Dataset':<20} {'Correct':>8} {'Total':>8} {'Accuracy':>10} {'Skipped':>8}")
    print(f"  {'-'*56}")
    total_correct = total_evaluated = 0
    for label, results in all_results.items():
        acc = compute_accuracy(results)
        total_correct += acc["correct"]
        total_evaluated += acc["total"]
        print(f"  {label:<20} {acc['correct']:>8} {acc['total']:>8} {acc['accuracy']:>10.1%} {acc['skipped']:>8}")
    overall = total_correct / total_evaluated if total_evaluated else 0.0
    print(f"  {'-'*56}")
    print(f"  {'Overall':<20} {total_correct:>8} {total_evaluated:>8} {overall:>10.1%}")
    print(f"{'='*65}\n")


# ---------------------------------------------------------------------------
# CSV export
# ---------------------------------------------------------------------------

def save_csv(all_results: dict, path: Path, tol: float) -> None:
    fieldnames = [
        "model", "dataset", "id", "entity", "depth",
        "question", "prompt", "ground_truth", "predicted_answer",
        "reasoning", "correct", "relative_error", "within_tol", "skipped",
    ]
    with open(path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        for model_name, datasets in all_results.items():
            for dataset_label, results in datasets.items():
                for r in results:
                    gt = r.get("ground_truth")
                    pred = r.get("predicted")
                    try:
                        gt = float(str(gt).replace(",", "")) if gt is not None else None
                    except (ValueError, TypeError):
                        gt = None
                    if gt is not None and pred is not None and gt != 0:
                        rel_err = abs(pred - gt) / abs(gt)
                    else:
                        rel_err = None
                    writer.writerow({
                        "model": model_name,
                        "dataset": dataset_label,
                        "id": r.get("id", ""),
                        "entity": r.get("entity", ""),
                        "depth": r.get("depth", ""),
                        "question": r.get("question", ""),
                        "prompt": r.get("prompt", ""),
                        "ground_truth": gt,
                        "predicted_answer": pred,
                        "reasoning": r.get("llm_response", ""),
                        "correct": r.get("correct", False),
                        "relative_error": f"{rel_err:.6f}" if rel_err is not None else "",
                        "within_tol": (rel_err is not None and rel_err <= tol),
                        "skipped": r.get("skip", False),
                    })


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def parse_args():
    parser = argparse.ArgumentParser(
        description="LLM evaluation on 90-Q financial QA with adversarially corrupted spreadsheets"
    )
    parser.add_argument(
        "--models", nargs="+", default=DEFAULT_MODELS,
        help="Model names to evaluate (default: Qwen/Qwen3.5-27B)",
    )
    parser.add_argument(
        "--datasets", nargs="+", choices=list(ADVERSARIAL_SHEETS.keys()),
        default=list(ADVERSARIAL_SHEETS.keys()),
        help=f"Which adversarial sheet variants to evaluate (default: all). Choices: {list(ADVERSARIAL_SHEETS.keys())}",
    )
    parser.add_argument(
        "--questions", type=str, default=str(DATASET_90Q),
        help="Path to the 90-Q questions JSON file",
    )
    parser.add_argument(
        "--limit", type=int, default=None,
        help="Max questions per dataset per model (default: all)",
    )
    parser.add_argument(
        "--tol", type=float, default=0.1,
        help="Relative tolerance for numeric correctness (default: 0.1 = 10%%)",
    )
    parser.add_argument(
        "--max-new-tokens", type=int, default=2048,
        help="Max new tokens per answer (default: 2048)",
    )
    parser.add_argument(
        "--output", type=str, default="output_llm/eval_adversarial_results.json",
        help="Path to save per-question results JSON",
    )
    parser.add_argument(
        "--csv", type=str, default="output_llm/eval_adversarial_results.csv",
        help="Path to save per-question results CSV",
    )
    return parser.parse_args()


def main():
    args = parse_args()

    print("Loading questions...")
    questions = load_json(Path(args.questions))
    print(f"  {len(questions)} questions loaded from {args.questions}")

    print("Loading sheet lookups...")
    sheet_lookups: dict[str, dict] = {}
    for label in args.datasets:
        sheet_path = ADVERSARIAL_SHEETS[label]
        if not sheet_path.exists():
            print(f"  WARNING: sheet not found, skipping '{label}': {sheet_path}")
            continue
        sheet_lookups[label] = build_sheet_lookup(load_sheet_csv(sheet_path))
        print(f"  [{label}] {len(sheet_lookups[label])} companies loaded from {sheet_path.name}")

    all_results: dict[str, dict[str, list]] = {}

    for model_name in args.models:
        print(f"\n{'='*65}")
        print(f"  Evaluating model: {model_name}")
        print(f"{'='*65}")

        model_results: dict[str, list] = {}

        for label, sheet_lookup in sheet_lookups.items():
            n = args.limit or len(questions)
            print(f"\n-- [{label}] ({n} questions) --")
            model_results[label] = evaluate(
                questions=questions,
                sheet_lookup=sheet_lookup,
                model_name=model_name,
                dataset_label=label,
                limit=args.limit,
                tol=args.tol,
                max_new_tokens=args.max_new_tokens,
            )

        print_summary(model_name, model_results)
        all_results[model_name] = {
            label: results
            for label, results in model_results.items()
        }
        all_results[model_name]["_accuracy"] = {
            label: compute_accuracy(results)
            for label, results in model_results.items()
        }

    # Save results
    ts = datetime.now().strftime("%Y%m%d_%H%M%S")

    output_path = Path(args.output).with_stem(Path(args.output).stem + f"_{ts}")
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w") as f:
        json.dump(all_results, f, indent=2, default=str)
    print(f"Results saved to {output_path}")

    csv_path = Path(args.csv).with_stem(Path(args.csv).stem + f"_{ts}")
    csv_path.parent.mkdir(parents=True, exist_ok=True)
    save_csv(
        {m: {k: v for k, v in d.items() if k != "_accuracy"} for m, d in all_results.items()},
        csv_path, tol=args.tol,
    )
    print(f"CSV saved to {csv_path}")

    # Cross-model comparison
    if len(all_results) > 1:
        labels = [l for l in sheet_lookups]
        header = f"{'Model':<25}" + "".join(f"{l:>12}" for l in labels)
        print(f"\n=== Model Comparison ===\n{header}")
        print("-" * (25 + 12 * len(labels)))
        for m, r in all_results.items():
            row = f"{m:<25}"
            for label in labels:
                acc = r["_accuracy"].get(label, {}).get("accuracy", 0.0)
                row += f"{acc:>12.1%}"
            print(row)


if __name__ == "__main__":
    main()
